def collect_worker_outputs(reports_dir: str = "Reports/agy") -> dict:
    """w01: Collects outputs and status from all 24 active worker runners."""
    collected = {}
    worker_accounts = ["acc0", "acc1", "acc2", "acc3", "acc4", "acc5", "acc7", "acc8"]

    for acc in worker_accounts:
        acc_dir = os.path.join(reports_dir, acc)
        runner_reports = []
        if os.path.isdir(acc_dir):
            for fname in os.listdir(acc_dir):
                if fname.endswith(".txt") or fname.endswith(".md"):
                    runner_reports.append(fname)
        collected[acc.upper()] = {
            "account": acc.upper(),
            "expected_runners": 3,
            "reports_found": len(runner_reports),
            "files": runner_reports,
            "status": "ready",
        }
    return collected


def run_aggregator_gates() -> tuple[bool, str]:
    """w02: Executes Tools/run_gates.py and check_changelog.py."""
    print("ACC6-w02: Executing Tools/run_gates.py...")
    proc_gates = subprocess.run([sys.executable, "Tools/run_gates.py"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, check=False)
    gates_ok = proc_gates.returncode == 0

    print("ACC6-w02: Executing Tools/check_changelog.py...")
    proc_cl = subprocess.run([sys.executable, "Tools/check_changelog.py"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, check=False)
    cl_ok = proc_cl.returncode == 0

    combined_output = f"=== RUN GATES OUTPUT ===\n{proc_gates.stdout}\n=== CHANGELOG OUTPUT ===\n{proc_cl.stdout}"
    return (gates_ok and cl_ok), combined_output


